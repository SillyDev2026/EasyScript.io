import {DEFINITIONS,generate,lint,traverse} from "./engine.js";

const LUAU_ONLY=new Set(["service","playerJoined","playerLeaving","leaderstat","remoteReceived","datastoreGet","datastoreSet"]);
const CLIENT_ONLY=new Set(["playerLocal","remoteFireServer","remoteClientEvent","remoteInvokeServer","uiButtonClick","uiFocusLost","eventRenderStep"]);
const SERVER_ONLY=new Set(["datastoreGet","datastoreSet","remoteFireClient","remoteFireAll","remoteMakeEvent","remoteReceived","playerKick"]);
const DECLARATIONS=new Set(["variable","array","random","clamp","concat","length","listSize","instanceFind","instanceWait","instanceClass","instanceChildren","instanceDescendants","instanceClone","instanceAncestor","instanceIsA","instanceFullName","playerLocal","playerCharacter","playerHumanoid","playerFromCharacter","playerCount","playerGetById","vector3New","vector2New","colorRGB","colorHSV","cframeNew","udim2Scale","udim2Offset","vectorDistance","vectorLerp","vectorMagnitude","remoteInvokeServer","jsonEncode","jsonDecode","getTime","getUnixTime","getAttributeChildren","datastoreGet","getAttribute","jsQuery","jsQueryAll","jsJsonParse","jsJsonStringify","jsStorageRead","jsFetchJson","globalRead"]);
const IDENT=/^[A-Za-z_]\w*$/;
function blocksOf(project){const out=[];traverse(project.blocks||[],block=>out.push(block));return out;}
export function formatTutorialSource(source,{indent=4,header=true,spacing="readable"}={}){
  const spaces=Math.min(8,Math.max(2,Math.floor(Number(indent)||4)));
  const lines=String(source).replace(/\r\n?/g,"\n").split("\n");
  let result=[];
  for(let i=0;i<lines.length;i++){
    if(!header&&i===0&&/^(--|\/\/) Generated by EasyScript/.test(lines[i]))continue;
    const match=lines[i].match(/^( *)(.*)$/),depth=Math.floor(match[1].length/4);
    if(spacing==="compact"&&!match[2].trim()&&result.length)continue;
    result.push(" ".repeat(depth*spaces)+match[2]);
  }
  if(spacing==="compact")result=result.filter((line,i)=>line.trim()||i===0);
  return result.join("\n").replace(/^\n+/,"").replace(/\n*$/,"\n");
}
export function inspectVariables(project){
  const blocks=blocksOf(project),vars=new Map();
  for(const block of blocks){
    const f=block.fields||{},type=block.type;
    let name=null,kind="local";
    if(type.startsWith("global")&&["globalWrite","globalRead","globalIncrease","globalDelete"].includes(type)){
      name=f.key;kind=project.language==="javascript"?"globalThis":"script local";
    }else if(DECLARATIONS.has(type))name=f.name;
    if(!name||!IDENT.test(name))continue;
    const entry=vars.get(name)||{name,kind,definitions:0,updates:0,mentions:0,blockIds:[]};
    if(type==="set"||type==="increment"||type==="globalWrite"||type==="globalIncrease"||type==="globalDelete")entry.updates++;
    else entry.definitions++;
    entry.blockIds.push(block.id);vars.set(name,entry);
  }
  for(const block of blocks){
    const values=Object.entries(block.fields||{});
    for(const entry of vars.values()){
      const word=new RegExp("(^|[^A-Za-z0-9_])"+entry.name+"(?=$|[^A-Za-z0-9_])","g");
      for(const [field,val] of values){
        if(field==="name"||field==="key")continue;
        entry.mentions+=(String(val).match(word)||[]).length;
      }
    }
  }
  return [...vars.values()].sort((a,b)=>a.name.localeCompare(b.name));
}
export function inspectServices(project){
  if(project.language==="javascript")return [];
  const source=generate(project);
  const map=new Map();
  for(const match of source.matchAll(/(?:game:GetService|game\.GetService)\(\s*"([^"]+)"\s*\)/g)){
    const name=match[1];
    map.set(name,(map.get(name)||0)+1);
  }
  return [...map].map(([name,references])=>({name,references})).sort((a,b)=>a.name.localeCompare(b.name));
}
export function scriptChecklist(project,kind="Script"){
  const blocks=blocksOf(project),types=new Set(blocks.map(x=>x.type));
  const items=[];
  const push=(status,label,details)=>items.push({status,label,details});
  const issues=lint(project);
  const errors=issues.filter(x=>x.severity==="error").length;
  push(errors?"warning":"pass","Block validation",errors?errors+" generator errors require attention.":"No errors detected by the limited block checker.");
  const client=[...types].filter(t=>CLIENT_ONLY.has(t));
  const server=[...types].filter(t=>SERVER_ONLY.has(t));
  if(kind==="LocalScript"&&server.length)push("warning","Server APIs in a LocalScript",server.join(", ")+". Move server code to a server Script.");
  if(kind==="Script"&&client.length)push("warning","Client APIs in a Script",client.join(", ")+". Move UI or local-player input to a LocalScript.");
  if(kind==="ModuleScript"&&[...types].some(t=>t==="playerJoined"||t==="remoteReceived"))push("warning","ModuleScript execution","ModuleScripts do not run on their own. Require this module from an appropriate Script.");
  if(types.has("remoteReceived")||types.has("remoteFireServer"))push("warning","RemoteEvent boundary","Validate incoming data, authorization and rate limits on the server.");
  if(types.has("datastoreGet")||types.has("datastoreSet"))push("warning","DataStore persistence","Use server Scripts, protected calls, budgets, retries and a separate test experience.");
  if([...types].some(t=>t.startsWith("global")))push("note","Variable scope","Script locals do not automatically share data with other scripts, clients or servers.");
  if(project.language==="javascript"&&[...types].some(t=>LUAU_ONLY.has(t)))push("warning","Mixed target languages","Roblox-only blocks are not executable as JavaScript.");
  if(!items.some(x=>x.status==="warning"))push("note","Runtime verification","Test exported source in its actual Roblox or browser runtime.");
  return items;
}
export function compareSources(previous,current,maxLines=2000){
  const old=String(previous).split("\n").slice(0,maxLines);
  const now=String(current).split("\n").slice(0,maxLines);
  let prefix=0,suffix=0;
  while(prefix<old.length&&prefix<now.length&&old[prefix]===now[prefix])prefix++;
  while(suffix<old.length-prefix&&suffix<now.length-prefix&&old[old.length-1-suffix]===now[now.length-1-suffix])suffix++;
  const removed=old.slice(prefix,old.length-suffix);
  const added=now.slice(prefix,now.length-suffix);
  return {changed:!!(removed.length||added.length),unchanged:prefix+suffix,
    removed:removed.map(text=>({kind:"removed",text})),
    added:added.map(text=>({kind:"added",text})),
    truncated:String(previous).split("\n").length>maxLines||String(current).split("\n").length>maxLines};
}
export function projectMetrics(project){
  const source=generate(project),blocks=blocksOf(project);
  const codeLines=source.split("\n").filter(line=>line.trim()&&!/^\s*(--|\/\/)/.test(line)).length;
  const branchBlocks=blocks.filter(b=>(DEFINITIONS[b.type]?.branches||[]).length).length;
  return {blocks:blocks.length,codeLines,branchBlocks,services:inspectServices(project).length,
    variables:inspectVariables(project).length};
}
