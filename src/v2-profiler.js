// A manual Roblox Studio microprofiler scaffold; does not run in a web browser.
export function robloxProfilerModule(){
 return [
  "-- EasyScript v2 Profiler · ModuleScript for Studio testing",
  "-- Use Profiler.measure(label, function() ... end) around the work you want timed.",
  "local Profiler = {}",
  "local samples = {}",
  "",
  "function Profiler.measure(label: string, callback: (...any) -> ...any, ...: any)",
  '    assert(type(label) == "string" and #label > 0, "Profile label is required")',
  '    assert(type(callback) == "function", "Profiler needs a callback")',
  "    local started = os.clock()",
  "    local outcome = table.pack(pcall(callback, ...))",
  "    local elapsedMs = (os.clock() - started) * 1000",
  "    local sample = samples[label]",
  "    if not sample then",
  "        sample = {count = 0, totalMs = 0, maxMs = 0, failures = 0}",
  "        samples[label] = sample",
  "    end",
  "    sample.count += 1",
  "    sample.totalMs += elapsedMs",
  "    sample.maxMs = math.max(sample.maxMs, elapsedMs)",
  "    if not outcome[1] then",
  "        sample.failures += 1",
  "        error(outcome[2], 0)",
  "    end",
  "    return table.unpack(outcome, 2, outcome.n)",
  "end",
  "",
  "function Profiler.snapshot()",
  "    local result = {}",
  "    for label, record in pairs(samples) do",
  "        result[label] = {",
  "            count = record.count,",
  "            totalMs = record.totalMs,",
  "            averageMs = record.count > 0 and record.totalMs / record.count or 0,",
  "            maxMs = record.maxMs,",
  "            failures = record.failures,",
  "        }",
  "    end",
  "    return result",
  "end",
  "",
  "function Profiler.reset()",
  "    table.clear(samples)",
  "end",
  "",
  "return Profiler",
  ""
 ].join("\n");
}
export function robloxProfilerExample(){
 return [
  "-- Example server Script · require the Profiler ModuleScript in the same folder",
  "local Profiler = require(script.Parent:WaitForChild(\"Profiler\"))",
  "",
  "local output = Profiler.measure(\"Sum calculation\", function()",
  "    local total = 0",
  "    for index = 1, 1000 do",
  "        total += index",
  "    end",
  "    return total",
  "end)",
  'print("Result", output)',
  'print("Profiler snapshot", Profiler.snapshot())',
  "-- Sampling adds overhead; run real load tests on an appropriate Studio server.",
  ""
 ].join("\n");
}
