// Presentation-only formatting for generated Luau / JavaScript source.
// Never executes expressions or rewrites program tokens.
const STYLES=["raw","readable","compact"];
export const DEFAULT_CODE_PREFS=Object.freeze({style:"readable",labels:false});
export function normalizeCodePrefs(input={}){
 const raw=input&&typeof input==="object"?input:{};
 return {style:STYLES.includes(raw.style)?raw.style:"readable",labels:raw.labels===true};
}
const unsafeMultiline=source=>/\x60|\[\[|\[=\[/.test(source); // template strings and Luau long strings
const sectionLine=(trimmed,js)=>js?
 /^(?:async function |function |(?:const |let )?[A-Za-z_$][\w$]*\s*=\s*async\s*\(|(?:if |for |while |switch |try\b)|.*\.addEventListener\(|.*\.forEach\()/.test(trimmed):
 /^(?:local function |function |(?:if |for |while |repeat\b)|.*:Connect\(function\(|.*\.On(?:Server|Client)Invoke\s*=\s*function\()/.test(trimmed);
const indentSize=line=>line.length-line.trimStart().length;
export function polishSource(source,language="luau",prefs={}){
 const {style}=normalizeCodePrefs(prefs),text=String(source??"");
 if(style==="raw"||unsafeMultiline(text))return text;
 const js=language==="javascript",lines=text.replace(/\r\n?/g,"\n").split("\n");
 const cleaned=[];
 for(const original of lines){
  const line=original.replace(/[ \t]+$/g,"");
  if(!line.trim()){
   if(style==="compact")continue;
   if(cleaned.length&&cleaned[cleaned.length-1]!=="")cleaned.push("");
   continue;
  }
  const trimmed=line.trim(),isSection=sectionLine(trimmed,js);
  const last=cleaned.length?cleaned[cleaned.length-1]:"";
  const minIndent=js?4:0;
  if(style==="readable"&&isSection&&last&&last.trim()&&
     indentSize(line)===minIndent&&indentSize(last)===minIndent&&
     !/^(?:\/\/|--)\s*Generated by EasyScript/.test(last.trim())&&
     !/^(?:local (?:Players|DataStoreService)\s*=|local \w+Store\s*=)/.test(last.trim()))
   cleaned.push("");
  cleaned.push(line);
 }
 while(cleaned.length&&cleaned[0]==="")cleaned.shift();
 while(cleaned.length&&cleaned[cleaned.length-1]==="")cleaned.pop();
 return cleaned.join("\n")+"\n";
}
export function annotateCodeProject(project,DEFINITIONS){
 const original=project.blocks||[],annotated=[];
 for(const block of original){
  if(block.type!=="comment"){
   const title=DEFINITIONS[block.type]?.name||block.type;
   annotated.push({id:"label_"+block.id,type:"comment",fields:{text:"BLOCK: "+String(title).replace(/[\r\n]/g," ")}});
  }
  annotated.push(block);
 }
 return {...project,blocks:annotated};
}
export function polishedProjectSource(project,generate,DEFINITIONS,prefs={}){
 const options=normalizeCodePrefs(prefs);
 const sourceProject=options.labels?annotateCodeProject(project,DEFINITIONS):project;
 return polishSource(generate(sourceProject),project.language,options);
}
export function countCodeMetrics(code){
 const source=String(code??""),lines=source.trimEnd().split("\n");
 return {lines:source?lines.length:0,
  comments:lines.filter(x=>/^\s*(?:--|\/\/)/.test(x)).length,
  blank:lines.filter(x=>!x.trim()).length,chars:source.length};
}
