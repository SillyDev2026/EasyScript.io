import test from "node:test";
import assert from "node:assert/strict";
import vm from "node:vm";
import {readFileSync} from "node:fs";
import {VERSION,DEFINITIONS,projectTemplate,addBlock,generate,lint,simulate} from "../src/engine.js";
import {DEFAULT_CODE_PREFS,normalizeCodePrefs,polishSource,annotateCodeProject,polishedProjectSource,countCodeMetrics} from "../src/code-polish.js";

test("v2.3 readable presentation never changes statements or indentation",()=>{
 assert.equal(VERSION,"2.3.0");
 const p=projectTemplate("blank"),a=addBlock(p,"variable"),f=addBlock(p,"function");
 a.fields.name="Score";f.fields.name="greet";
 addBlock(p,"print",f.id,"body").fields.value='"hello"';
 const raw=generate(p),formatted=polishedProjectSource(p,generate,DEFINITIONS);
 assert.match(formatted,/local function greet/);
 assert.match(formatted,/    print\("hello"\)/);
 assert.ok(formatted.includes('local Score = 100'));
 assert.equal(formatted.endsWith("\n"),true);
 assert.equal(polishSource(formatted,"luau"),formatted,"readable mode is idempotent");
 assert.deepEqual(p.blocks.map(b=>b.type),["variable","function"],"project unchanged");
});
test("optional section labels add comments without changing JS semantics",()=>{
 const p=projectTemplate("blank");p.language="javascript";
 addBlock(p,"variable").fields.name="items";addBlock(p,"print").fields.value='"yes"';
 const raw=generate(p);
 const presented=polishedProjectSource(p,generate,DEFINITIONS,{style:"readable",labels:true});
 assert.match(presented,/\/\/ BLOCK: Create variable/);
 assert.match(presented,/\/\/ BLOCK: Print/);
 assert.doesNotThrow(()=>new vm.Script(presented));
 assert.doesNotThrow(()=>new vm.Script(raw));
 assert.equal(p.blocks.length,2,"annotation must not mutate editable script");
});
test("readable, compact and original source show distinct but safe whitespace",()=>{
 const raw='-- Generated by EasyScript v2.3.0\n\nlocal Coins = 100   \n\n\nprint(Coins)\n';
 assert.equal(polishSource(raw,"luau",{style:"raw"}),raw);
 const compact=polishSource(raw,"luau",{style:"compact"});
 assert.doesNotMatch(compact.trimEnd(),/^\s*$/m);
 assert.match(compact,/local Coins = 100\nprint\(Coins\)/);
 const readable=polishSource(raw,"luau");
 assert.match(readable,/local Coins = 100\n\nprint/);
 assert.equal(polishSource(compact,"luau",{style:"compact"}),compact);
});
test("long multiline literals remain untouched to preserve program semantics",()=>{
 const lua='local msg = [[a\n\nb]]\nprint(msg)\n';
 const js='const text = '+String.fromCharCode(96)+'a\n\nb'+String.fromCharCode(96)+';\nconsole.log(text)\n';
 assert.equal(polishSource(lua,"luau",{style:"compact"}),lua);
 assert.equal(polishSource(js,"javascript",{style:"compact"}),js);
});
test("bad code UI preferences recover to safe choices",()=>{
 assert.deepEqual(normalizeCodePrefs(null),DEFAULT_CODE_PREFS);
 assert.deepEqual(normalizeCodePrefs({style:"unknown",labels:"yes"}),DEFAULT_CODE_PREFS);
 assert.deepEqual(normalizeCodePrefs({style:"compact",labels:true}),{style:"compact",labels:true});
 const metrics=countCodeMetrics("-- hi\n\nlocal Coins = 1\n");
 assert.deepEqual(metrics,{lines:3,comments:1,blank:1,chars:23});
});
test("disabled blocks do not execute in the offline simulator",()=>{
 const p=projectTemplate("blank");
 const b=addBlock(p,"print");b.fields.value='"hidden"';b.disabled=true;
 const active=addBlock(p,"print");active.fields.value='"visible"';
 const result=simulate(p);
 assert.equal(result.error,null);
 assert.deepEqual(result.messages,["visible"]);
 const f=addBlock(p,"function");f.fields.name="ignored";f.disabled=true;
 addBlock(p,"print",f.id,"body").fields.value='"wrong"';
 const call=addBlock(p,"call");call.fields.name="ignored";
 assert.match(simulate(p).error,/Unknown function/);
});
test("both conditional branches create independent Roblox leaderstats folders",()=>{
 const p=projectTemplate("blank");
 const event=addBlock(p,"playerJoined"),branch=addBlock(p,"if",event.id,"body");
 branch.fields.left="player.UserId";branch.fields.right="0";branch.fields.operator=">";
 addBlock(p,"leaderstat",branch.id,"then").fields.name="Coins";
 addBlock(p,"leaderstat",branch.id,"else").fields.name="Wins";
 const code=generate(p);
 assert.equal((code.match(/Instance\.new\("Folder"\)/g)||[]).length,2);
 assert.equal((code.match(/\.Name = "leaderstats"/g)||[]).length,2);
 assert.equal(lint(p).filter(x=>x.severity==="error").length,0);
});
