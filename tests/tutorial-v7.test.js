import test from "node:test";
import assert from "node:assert/strict";
import {projectTemplate,addBlock,generate,lint} from "../src/engine.js";
import {formatTutorialSource,inspectVariables,inspectServices,scriptChecklist,compareSources,projectMetrics} from "../src/ultra-plus-engine.js";

test("tutorial leaderstats produces readable names and four-space indentation",()=>{
  const source=generate(projectTemplate("leaderstats"));
  assert.match(source,/^local Players = game:GetService\("Players"\)/m);
  assert.match(source,/^Players\.PlayerAdded:Connect\(function\(player\)$/m);
  assert.match(source,/^    local leaderstats = Instance.new\("Folder"\)$/m);
  assert.match(source,/^    local coins = Instance.new\("IntValue"\)$/m);
  assert.match(source,/^    coins\.Value = 0$/m);
  assert.doesNotMatch(source,/leaderstats__|stat__|FindFirstChild\("leaderstats"\)/);
  assert.doesNotMatch(source,/_G/);
});
test("DataStore tutorial hoists service and store and reuses simple stat names",()=>{
  const source=generate(projectTemplate("playerData"));
  const header=source.slice(0,source.indexOf("Players.PlayerAdded:Connect"));
  assert.match(header,/local Players = game:GetService\("Players"\)/);
  assert.match(header,/local DataStoreService = game:GetService\("DataStoreService"\)/);
  assert.match(header,/local playerDataStore = DataStoreService:GetDataStore\("PlayerDataV1"\)/);
  assert.equal((source.match(/GetDataStore\(/g)||[]).length,1);
  assert.match(source,/^    local success, savedCoins = pcall\(function\(\)$/m);
  assert.match(source,/^        return playerDataStore:GetAsync\(tostring\(player\.UserId\)\)$/m);
  assert.match(source,/^    local leaderstats = Instance.new\("Folder"\)$/m);
  assert.match(source,/^    local coins = Instance.new\("IntValue"\)$/m);
  assert.match(source,/^    coins\.Value = savedCoins or 0$/m);
  assert.doesNotMatch(source,/SavedCoinsStore|leaderstats__|stat__/);
});
test("two stats reuse one Folder and do not collide",()=>{
  const p=projectTemplate("blank"),event=addBlock(p,"playerJoined");
  addBlock(p,"leaderstat",event.id,"body");
  addBlock(p,"leaderstat",event.id,"body");
  const code=generate(p);
  assert.equal((code.match(/Instance.new\("Folder"\)/g)||[]).length,1);
  assert.match(code,/local coins = Instance.new\("IntValue"\)/);
  assert.match(code,/local coins2 = Instance.new\("IntValue"\)/);
});
test("script locals do not emit _G and use an inline assignment",()=>{
  const p=projectTemplate("globalCounter"),code=generate(p);
  assert.match(code,/^local Coins = 0$/m);
  assert.match(code,/^Coins = \(Coins or 0\) \+ \(1\)$/m);
  assert.doesNotMatch(code,/_G/);
  assert.ok(lint(p).some(issue=>issue.message.includes("Script locals")));
});
test("read before write preserves the original execution order",()=>{
  const p=projectTemplate("blank");
  addBlock(p,"globalRead");
  addBlock(p,"globalWrite");
  const code=generate(p);
  assert.match(code,/local Coins = nil/);
  assert.ok(code.indexOf("Coins = Coins or 0")<code.indexOf("Coins = 0"));
});
test("code style formatter changes presentation, not program contents",()=>{
  const src=generate(projectTemplate("leaderstats"));
  const out=formatTutorialSource(src,{header:false,indent:2,spacing:"compact"});
  assert.doesNotMatch(out,/Generated by/);
  assert.match(out,/^  local leaderstats = Instance.new\("Folder"\)$/m);
  assert.match(out,/^  local coins = Instance.new\("IntValue"\)$/m);
  assert.doesNotMatch(out,/local coins =\s*\n/);
});
test("Variable Explorer and Service Explorer report names without executing source",()=>{
  const p=projectTemplate("playerData");
  assert.ok(inspectVariables(p).some(x=>x.name==="savedCoins"));
  const services=inspectServices(p).map(x=>x.name);
  assert.ok(services.includes("Players"));
  assert.ok(services.includes("DataStoreService"));
  const metrics=projectMetrics(p);
  assert.ok(metrics.blocks>=3&&metrics.codeLines>10);
});
test("runtime checklist warns about DataStore and client-only APIs",()=>{
  const p=projectTemplate("playerData");
  const checks=scriptChecklist(p,"LocalScript");
  assert.ok(checks.some(x=>x.label.includes("Server APIs")));
  assert.ok(checks.some(x=>x.label.includes("DataStore")));
});
test("Version Compare returns added and removed source lines",()=>{
  const a=generate(projectTemplate("blank")),b=generate(projectTemplate("leaderstats"));
  const diff=compareSources(a,b);
  assert.equal(diff.changed,true);
  assert.ok(diff.removed.length>0&&diff.added.length>0);
  assert.equal(compareSources(a,a).changed,false);
});
test("Luau example uses one line per assignment even with nested blocks",()=>{
  const p=projectTemplate("playerData");
  const source=generate(p);
  assert.doesNotMatch(source,/=\s*\n\s*\w/);
  assert.doesNotMatch(source,/local \w+__\w+/);
  assert.ok(source.split("\n").some(x=>x.startsWith("        return")));
});
