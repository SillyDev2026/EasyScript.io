test("workspace merge preserves files and renames duplicate names",()=>{
 const base=createWorkspace(projectTemplate("blank"));
 const incoming=createWorkspace(projectTemplate("blank"));
 addFile(incoming,"Inventory","ModuleScript");
 const result=mergeWorkspaces(base,incoming);
 assert.equal(result.added,2);
 assert.equal(result.workspace.files.length,3);
 assert.equal(new Set(result.workspace.files.map(x=>x.name.toLowerCase())).size,3);
 assert.equal(base.files.length,1,"input should not mutate");
});
