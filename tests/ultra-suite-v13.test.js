test("custom SDK definitions can be saved then reloaded from browser-like storage",()=>{
 const storage=memory();
 registerCustomDefinition({id:"hello_saved",label:"Hello saved",fields:{message:'"Okay"'},
   luau:"print({{message}})",javascript:"console.log({{message}});"},DEFINITIONS);
 saveCustomDefinitions(storage);
 const loaded=loadCustomDefinitions(storage,DEFINITIONS);
 assert.ok(loaded>=1);
 assert.ok(listCustomDefinitions().some(x=>x.id==="hello_saved"));
});
