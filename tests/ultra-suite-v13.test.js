test("versioned schema generator emits typed defaults and safe migration",()=>{
 const schema=dataSchemaModule("PlayerData",[
  {name:"Coins",type:"number",default:0},
  {name:"Name",type:"string",default:"Rook"},
  {name:"Onboarded",type:"boolean",default:"false"}
 ]);
 assert.match(schema.code,/local PlayerData = {}/);
 assert.match(schema.code,/Coins = 0/);
 assert.match(schema.code,/Onboarded = false/);
 assert.match(schema.code,/function PlayerData.Migrate\(input\)/);
 assert.match(schema.code,/type\(source.Coins\) == "number"/);
 assert.match(schema.code,/return PlayerData/);
});
test("schema rejects invalid keys, collisions and unsupported types",()=>{
 assert.throws(()=>dataSchemaModule("PlayerData",[]),/1–40/);
 assert.throws(()=>dataSchemaModule("Invalid Name",[{name:"Coins",type:"number",default:0}]),/identifier/);
 assert.throws(()=>dataSchemaModule("Good",[{name:"Coins",type:"number",default:0},{name:"Coins",type:"number",default:5}]),/duplicate/);
 assert.throws(()=>dataSchemaModule("Good",[{name:"Coins",type:"Instance",default:0}]),/Unsupported/);
});
