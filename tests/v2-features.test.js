test("offline patches review additions/changes without mutating initial files",()=>{
 const before=createWorkspace(projectTemplate("blank"));
 const after=structuredClone(before);
 addFile(after,"Inventory","ModuleScript");
 const result=reviewWorkspaceChanges(before,after);
 assert.equal(result.summary.added,1);
 const patch=createWorkspacePatch(before,after);
 assert.equal(patch.changes.length,1);
 assert.equal(inspectWorkspacePatch(before,patch).compatible,true);
 const next=applyWorkspacePatch(before,patch);
 assert.equal(next.files.length,2);
 assert.equal(before.files.length,1);
});
test("offline patches reject divergent baselines and tampered targets",()=>{
 const before=createWorkspace(),after=structuredClone(before);
 addFile(after,"NewModule","ModuleScript");
 const patch=createWorkspacePatch(before,after);
 const diverged=structuredClone(before);diverged.name="An independent edit";
 assert.equal(inspectWorkspacePatch(diverged,patch).compatible,false);
 assert.throws(()=>applyWorkspacePatch(diverged,patch),/Workspace changed/);
 const changed=structuredClone(patch);
 changed.workspace.name="Tampered";
 assert.throws(()=>inspectWorkspacePatch(before,changed),/checksum/);
});
