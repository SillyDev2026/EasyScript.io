import test from "node:test";
import assert from "node:assert/strict";
import vm from "node:vm";
import {DEFINITIONS,VERSION,projectTemplate,addBlock,generate,lint,simulate,sanitizeProject} from "../src/engine.js";
import {ROBLOX_TYPES} from "../src/roblox-blocks.js";
import {JS_TYPES} from "../src/javascript-blocks.js";
import {PACKS} from "../src/packs.js";

test("v0.6 exposes 128 blocks with a Luau-heavy catalog",()=>{
  assert.equal(VERSION,"2.4.0");
  assert.equal(Object.keys(DEFINITIONS).length,249);
  assert.ok(ROBLOX_TYPES.size>=70);
  assert.ok(JS_TYPES.size>=15);
});
test("every registered block is translated or explicitly marked unsupported",()=>{
  for(const language of ["luau","javascript"]){
    for(const type of Object.keys(DEFINITIONS)){
      const project=projectTemplate("blank");project.language=language;
      addBlock(project,type);
      const result=generate(project);
      assert.ok(result.length>30,type+" output missing");
      assert.doesNotMatch(result,/Unsupported block:/,type+" missing compiler");
      assert.doesNotMatch(result,/undefined\s*\(/,type+" undefined compiler");
      if(language==="javascript"){
        assert.doesNotThrow(()=>new vm.Script(result),type+" produces invalid JavaScript");
      }
    }
  }
});
test("all assignments are on one physical line, even with accidental pasted newlines",()=>{
  for(const language of ["luau","javascript"]){
    for(const type of Object.keys(DEFINITIONS)){
      const p=projectTemplate("blank");p.language=language;
      const b=addBlock(p,type);
      for(const key of Object.keys(b.fields)){
        if(["value","amount","x","min","r","seconds","duration"].includes(key))b.fields[key]+="\n   ";
      }
      const source=generate(p);
      assert.ok(!source.includes(" = \n"),type+" generated split assignment");
      assert.ok(!source.includes(" = \r"),type+" generated split assignment");
      assert.ok(!source.includes(" = \u2028"),type+" generated split assignment");
    }
  }
});
test("script globals are ordinary Luau locals and JavaScript globalThis",()=>{
  const p=projectTemplate("globalCounter");
  const luau=generate(p);
  assert.match(luau,/local Coins = 0/);
  assert.match(luau,/Coins = \(Coins or 0\) \+ \(1\)/);
  assert.doesNotMatch(luau,/_G/);
  assert.doesNotMatch(luau,/local Coins =\s*\n/);
  p.language="javascript";
  const js=generate(p);
  assert.match(js,/globalThis\["Coins"\] = 0/);
  assert.doesNotThrow(()=>new vm.Script(js));
});

test("all starter packs produce an appropriate source language and diagnostics",()=>{
  assert.equal(PACKS.length,17);
  for(const item of PACKS){
    const p=projectTemplate(item.id);
    assert.equal(p.language,item.language,item.id);
    assert.ok(p.blocks.length>0,item.id);
    const source=generate(p);
    assert.ok(source.includes(item.language==="luau"?"Generated by EasyScript":"Generated by EasyScript"));
    if(item.language==="javascript")assert.doesNotThrow(()=>new vm.Script(source),item.id);
  }
});
test("new event blocks emit nested body and close subscriptions",()=>{
  for(const type of ["eventChildAdded","eventProximity","eventHeartbeat","uiButtonClick","remoteClientEvent","taskDelay","taskDefer"]){
    const p=projectTemplate("blank"),event=addBlock(p,type);
    const log=addBlock(p,"print",event.id,"body");log.fields.value='"Inside"';
    const source=generate(p);
    assert.match(source,/print\("Inside"\)/);
    assert.match(source,/end\)/);
  }
});
test("DataStore code hoists its store and uses distinct, readable status names",()=>{
  const p=projectTemplate("blank");
  addBlock(p,"datastoreSet");addBlock(p,"datastoreSet");
  const source=generate(p);
  assert.equal((source.match(/GetDataStore\("PlayerDataV1"\)/g)||[]).length,1);
  assert.equal((source.match(/pcall\(function\(\)/g)||[]).length,2);
  const names=[...source.matchAll(/local (saveSuccess\d*), (saveError\d*) =/g)];
  assert.equal(names.length,2);
  assert.notEqual(names[0][1],names[1][1]);
});

test("newline expressions are flagged rather than silently accepted",()=>{
  const p=projectTemplate("blank");
  const block=addBlock(p,"variable");block.fields.value="5\n+ 3";
  assert.match(generate(p),/local Coins = 5 \+ 3/);
  assert.ok(lint(p).some(x=>x.severity==="error"&&x.message.includes("line break")));
  const imported=sanitizeProject(JSON.parse(JSON.stringify(p)));
  assert.match(generate(imported),/local Coins = 5 \+ 3/);
});
test("network and globals include targeted caveat warnings",()=>{
  const p=projectTemplate("blank");
  addBlock(p,"globalWrite");addBlock(p,"datastoreGet");addBlock(p,"remoteFireServer");
  const issues=lint(p);
  assert.ok(issues.some(x=>x.message.includes("Script locals")));
  assert.ok(issues.some(x=>x.message.includes("DataStore requests")));
  assert.ok(issues.some(x=>x.message.includes("LocalScript")));
});
test("simulator explicitly refuses new Roblox and browser blocks",()=>{
  const lua=projectTemplate("blank");addBlock(lua,"vector3New");
  const js=projectTemplate("blank");js.language="javascript";addBlock(js,"jsQuery");
  assert.match(simulate(lua).error,/Preview does not support/);
  assert.match(simulate(js).error,/Preview does not support/);
});
